"""Collect every distinct paragraph across the user's resume files, with where each one appears.

This is step one of building the master resume: profile/extracted.yaml lists each paragraph once,
with a stable id. Grouping those ids into roles and achievements (profile/resume_groups.yaml) is
done by hand with the user, and `build` turns the groups into profile/master_resume.yaml.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from pathlib import Path

import yaml

from applier.resume.sources import SourceDoc, normalize, paragraph_id, read_sources


@dataclass
class ExtractedParagraph:
    id: str
    text: str
    kind: str
    contexts: list[str] = field(default_factory=list)
    sections: list[str] = field(default_factory=list)
    sources: list[str] = field(default_factory=list)


def extract(docs: list[SourceDoc]) -> list[ExtractedParagraph]:
    found: dict[str, ExtractedParagraph] = {}
    for doc in docs:
        for para in doc.paragraphs:
            if para.kind in ("name", "section"):
                continue
            pid = paragraph_id(para.text)
            item = found.get(pid)
            if item is None:
                item = found[pid] = ExtractedParagraph(pid, normalize(para.text), para.kind)
            if para.context and para.context not in item.contexts:
                item.contexts.append(para.context)
            if para.section and para.section not in item.sections:
                item.sections.append(para.section)
            if doc.name not in item.sources:
                item.sources.append(doc.name)
    return sorted(found.values(), key=lambda p: (p.kind, p.contexts[:1], p.text))


def write_extracted(path: Path, items: list[ExtractedParagraph]) -> None:
    data = [
        {"id": p.id, "kind": p.kind, "text": p.text, "contexts": p.contexts, "sections": p.sections,
         "sources": p.sources}
        for p in items
    ]
    path.write_text(
        "# Every distinct paragraph in profile/source, generated by `python -m applier profile extract`.\n"
        + yaml.safe_dump(data, allow_unicode=True, sort_keys=False, width=1000),
        encoding="utf-8",
    )


def read_extracted(path: Path) -> list[ExtractedParagraph]:
    data = yaml.safe_load(path.read_text(encoding="utf-8")) or []
    return [ExtractedParagraph(**item) for item in data]


def run_extract(source_dir: Path, out_file: Path) -> list[ExtractedParagraph]:
    items = extract(read_sources(source_dir))
    write_extracted(out_file, items)
    return items
